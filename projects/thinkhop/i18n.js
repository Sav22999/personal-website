    const LANGS = {en: 'English', it: 'Italiano', es: 'Español', fr: 'Français', de: 'Deutsch'};
    let lang = (function () {
        try {
            const s = JSON.parse(localStorage.getItem('thinkhop.lang'));
            if (s && T[s]) return s;
        } catch (e) { /* no storage */
        }
        const nav = ((navigator.languages && navigator.languages[0]) || navigator.language || 'en').slice(0, 2).toLowerCase();
        return T[nav] ? nav : 'en';
    })();

    function t(key, vars) {
        let s = (T[lang] && T[lang][key] !== undefined) ? T[lang][key] : (T.en[key] !== undefined ? T.en[key] : key);
        if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
        return s;
    }

    function setLang(l) {
        if (!T[l]) return;
        lang = l;
        try {
            localStorage.setItem('thinkhop.lang', JSON.stringify(l));
        } catch (e) { /* no storage */
        }
        document.documentElement.lang = l;
    }

    document.documentElement.lang = lang;

    /** Adds texts: {lang: {key: text}}. */
    const extend = more => Object.keys(more).forEach(l => Object.assign(T[l], more[l]));

    window.ThinkHopI18n = {t, setLang, getLang: () => lang, LANGS, extend};

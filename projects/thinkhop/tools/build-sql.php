<?php
/** Writes install/thinkhop.sql from lib/schema.php: php tools/build-sql.php */

declare(strict_types=1);

require __DIR__ . '/../lib/bootstrap.php';
require __DIR__ . '/../lib/schema.php';

$sql = "-- ThinkHop: tables for phpMyAdmin (generated by tools/build-sql.php). The prefix is th_.\n\n";
foreach (schema_statements('th_') as $statement) $sql .= preg_replace('/^ {8}/m', '', $statement) . ";\n\n";
$values = [];
$sort = 0;
foreach (AVATAR_ITEMS as $id => [$kind, $price]) $values[] = sprintf("('%s', '%s', %d, %d)", $id, $kind, $price, $sort++);
$sql .= "INSERT IGNORE INTO `th_avatar_items` (id, kind, price, sort) VALUES\n" . implode(",\n", $values) . ";\n\n";
$sql .= "INSERT INTO `th_meta` (k, v) VALUES ('schema_version', '" . SCHEMA_VERSION . "') ON DUPLICATE KEY UPDATE v = VALUES(v);\n";
file_put_contents(__DIR__ . '/../install/thinkhop.sql', $sql);
echo "install/thinkhop.sql written\n";

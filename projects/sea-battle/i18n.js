const LANGS = ['en', 'it', 'es', 'fr', 'de'];
let currentLang = 'en';

function getInitialLang() {
    try {
        const saved = localStorage.getItem('sb_lang');
        if (LANGS.includes(saved)) return saved;
    } catch (e) {
    }
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return LANGS.includes(nav) ? nav : 'en';
}

function t(key, vars = {}) {
    let str = (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
    for (const [k, v] of Object.entries(vars)) str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), () => v);
    return str;
}

function setLanguage(lang) {
    if (!LANGS.includes(lang)) lang = 'en';
    currentLang = lang;
    try {
        localStorage.setItem('sb_lang', lang);
    } catch (e) {
    }
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => el.textContent = t(el.dataset.i18n));
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => el.placeholder = t(el.dataset.i18nPlaceholder));
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.dataset.i18nTitle);
        el.setAttribute('aria-label', el.title);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
    document.querySelectorAll('.lang-btn, .lang-option').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === lang));
    const current = document.getElementById('lang-current');
    if (current) current.textContent = lang.toUpperCase();
    document.title = t('app_title') + (lang === 'en' ? ' (Battaglia Navale)' : '') + ' – Saverio Morelli';
    if (typeof onLanguageChanged === 'function') onLanguageChanged(lang);
}

const SUPPORTED_LANGS = Object.keys(translations);
let currentLang = 'en';

function t(key, params) {
    let str = (translations[currentLang] && translations[currentLang][key]) || translations.en[key] || key;
    if (params) {
        for (const [k, v] of Object.entries(params)) str = str.split(`{${k}}`).join(v);
    }
    return str;
}

function applyTranslations() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.dataset.i18nTitle);
        el.setAttribute('aria-label', el.title);
    });
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === currentLang));
}

function setLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) return;
    currentLang = lang;
    try { localStorage.setItem('chess_lang', lang); } catch (e) { /* storage unavailable */ }
    applyTranslations();
    if (typeof onLanguageChange === 'function') onLanguageChange();
}

function initI18n() {
    let saved = null;
    try { saved = localStorage.getItem('chess_lang'); } catch (e) { /* storage unavailable */ }
    if (SUPPORTED_LANGS.includes(saved)) currentLang = saved;
    else {
        const nav = (navigator.language || 'en').slice(0, 2);
        if (SUPPORTED_LANGS.includes(nav)) currentLang = nav;
    }
    document.querySelectorAll('.lang-btn').forEach(btn => btn.addEventListener('click', () => setLanguage(btn.dataset.lang)));
    applyTranslations();
}

    const LANGS = [['it', 'Italiano'], ['en', 'English']];

    function detect() {
        try {
            const v = JSON.parse(localStorage.getItem('gw.lang'));
            if (v === 'en' || DICT[v]) return v;
        } catch (e) { /* no storage */
        }
        const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
        return nav.toLowerCase().startsWith('it') ? 'it' : 'en';
    }

    const lang = detect();
    document.documentElement.lang = lang;

    /** Translates an English source string; {name} placeholders are filled from vars. */
    function t(s, vars) {
        let r = (lang !== 'en' && DICT[lang] && DICT[lang][s]) || s;
        if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
        return r;
    }

    function set(l) {
        try {
            localStorage.setItem('gw.lang', JSON.stringify(l));
        } catch (e) { /* no storage */
        }
        location.reload();
    }

    window.I18N = {lang, t, set, langs: LANGS, locale: lang === 'it' ? 'it-IT' : 'en-GB'};

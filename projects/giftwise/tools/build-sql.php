<?php
/** Regenerates install/giftwise.sql (tables for phpMyAdmin, prefix gw_): php tools/build-sql.php */
declare(strict_types=1);
require __DIR__ . '/../lib/bootstrap.php';
require __DIR__ . '/../lib/schema.php';
$p = 'gw_';
$out = ["-- Giftwise — tables for phpMyAdmin (prefix {$p}). Generated by tools/build-sql.php. Alternative to install-db.php.", 'SET NAMES utf8mb4;', ''];
foreach (schema_statements($p) as $sql) $out[] = preg_replace('/\n\s+/', "\n  ", trim($sql)) . ";\n";
$out[] = "INSERT INTO `{$p}meta` (k, v) VALUES ('schema_version', '" . SCHEMA_VERSION . "') ON DUPLICATE KEY UPDATE v = VALUES(v);";
file_put_contents(__DIR__ . '/../install/giftwise.sql', implode("\n", $out) . "\n");
echo "Written install/giftwise.sql\n";

let currentLang = 'en';

function getInitialLang() {
    try {
        const saved = localStorage.getItem('c4_lang');
        if (saved && translations[saved]) return saved;
        const nav = (navigator.language || '').slice(0, 2).toLowerCase();
        if (translations[nav]) return nav;
    } catch (e) {}
    return 'en';
}

function setLanguage(lang) {
    if (!translations[lang]) lang = 'en';
    currentLang = lang;
    try { localStorage.setItem('c4_lang', lang); } catch (e) {}
    document.documentElement.lang = lang;

    // Update data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) el.textContent = translations[lang][key];
    });

    // Update data-i18n-html elements
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (translations[lang][key]) el.innerHTML = translations[lang][key];
    });

    // Update data-i18n-placeholder elements
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang][key]) el.placeholder = translations[lang][key];
    });

    // Update data-i18n-title elements
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (translations[lang][key]) el.title = translations[lang][key];
    });

    // Update lang selector active states
    document.querySelectorAll('.lang-btn, .lang-option').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        btn.classList.toggle('active', btnLang === lang);
    });

    const langCurrent = document.getElementById('lang-current');
    if (langCurrent) langCurrent.textContent = lang.toUpperCase();

    // Custom app title in lobby header if needed
    const logoTitle = document.querySelector('.logo-title-text');
    if (logoTitle) {
        logoTitle.textContent = lang === 'it' ? 'Forza Quattro' : (translations[lang].app_title || 'Connect Four');
    }

    // Trigger language change callback if registered
    if (typeof onLanguageChanged === 'function') {
        onLanguageChanged(lang);
    }
}

function t(key, vars = {}) {
    let str = (translations[currentLang] && translations[currentLang][key]) ||
              (translations['en'] && translations['en'][key]) || key;
    for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), v);
    }
    return str;
}

function initI18n() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            setLanguage(lang);
        });
    });
    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.addEventListener('click', () => {
            const lang = opt.getAttribute('data-lang');
            setLanguage(lang);
            const overlay = document.getElementById('lang-overlay');
            if (overlay) overlay.classList.add('hidden');
        });
    });
}

if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initI18n);
    } else {
        initI18n();
    }
}

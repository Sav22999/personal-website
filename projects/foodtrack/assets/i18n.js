  const LANGS = [['it', 'Italiano'], ['en', 'English']];

  function detect() {
    try { const v = JSON.parse(localStorage.getItem('ft.lang')); if (v && DICT[v] || v === 'en') return v; } catch (e) { /* no storage */ }
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    return nav.toLowerCase().startsWith('it') ? 'it' : 'en';
  }
  const lang = detect();
  document.documentElement.lang = lang;

  /** Translates an English source string; {name} placeholders are filled from vars. */
  function t(s, vars) {
    let r = (lang !== 'en' && DICT[lang] && DICT[lang][s]) || s;
    if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return r;
  }

  /** Adds strings at run time (e.g. page-specific ones). */
  function extend(l, entries) { DICT[l] = Object.assign(DICT[l] || {}, entries); }

  function set(l) {
    try { localStorage.setItem('ft.lang', JSON.stringify(l)); } catch (e) { /* no storage */ }
    location.reload();
  }

  window.I18N = { lang, t, set, extend, langs: LANGS, locale: lang === 'it' ? 'it-IT' : 'en-GB' };

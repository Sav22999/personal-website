<?php
/**
 * Generates install/foodtrack.sql (tables + initial data) for a manual import in phpMyAdmin.
 * Run it from the command line after changing lib/schema.php or lib/seed.php:
 *
 *   php tools/build-sql.php
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }

require __DIR__ . '/../lib/bootstrap.php';
require __DIR__ . '/../lib/schema.php';
require __DIR__ . '/../lib/seed.php';
require __DIR__ . '/../lib/seed-en.php';

$p = $argv[1] ?? 'ft_';
if (!preg_match('/^[A-Za-z0-9_]{1,20}$/', $p)) { fwrite(STDERR, "Invalid prefix\n"); exit(1); }

function q($v): string
{
    if ($v === null) return 'NULL';
    if (is_int($v) || is_float($v)) return (string)$v;
    return "'" . str_replace(["\\", "'", "\n", "\r"], ["\\\\", "\\'", "\\n", "\\r"], (string)$v) . "'";
}

$out = [];
$out[] = '-- FoodTrack — database structure and initial data';
$out[] = '-- Generated by tools/build-sql.php on ' . gmdate('Y-m-d') . ' — table prefix: ' . $p;
$out[] = '--';
$out[] = '-- Import it ONCE, on an empty database. In phpMyAdmin: select the database, tab "Importa" (Import), choose this file, "Esegui".';
$out[] = '-- Alternatively open install-db.php in the browser: it runs these same queries and creates the master admin.';
$out[] = '--';
$out[] = '-- After a manual import: register from the app, then make your account the master admin with';
$out[] = "--   UPDATE `{$p}users` SET role = 10 WHERE email = 'your@email.com';";
$out[] = '-- (role: 1 = user, 9 = administrator, 10 = master admin — only one)';
$out[] = '';
$out[] = 'SET NAMES utf8mb4;';
$out[] = "SET time_zone = '+00:00';";
$out[] = '';
$out[] = '-- ---------------------------------------------------------------- tables';
foreach (schema_statements($p) as $sql) $out[] = $sql . ";\n";
$out[] = "INSERT INTO `{$p}meta` (k, v) VALUES ('schema_version', '" . SCHEMA_VERSION . "') ON DUPLICATE KEY UPDATE v = VALUES(v);";
$out[] = '';

$out[] = '-- ---------------------------------------------------------------- categories';
$sort = 0;
foreach (seed_categories() as $name => $tip) {
    $out[] = "INSERT IGNORE INTO `{$p}categories` (name, expiry_tip, sort) VALUES (" . q($name) . ', ' . q($tip) . ', ' . ($sort += 10) . ');';
}
$out[] = '';

$out[] = '-- ---------------------------------------------------------------- product catalog';
foreach (seed_products() as [$name, $icon, $cat, $unit, $tip]) {
    $out[] = "INSERT IGNORE INTO `{$p}products` (name, icon, category_id, default_unit, expiry_tip, active, created_at, updated_at) VALUES ("
        . q($name) . ', ' . q($icon) . ", (SELECT id FROM `{$p}categories` WHERE name = " . q($cat) . '), ' . q($unit) . ', ' . q($tip) . ', 1, UTC_TIMESTAMP(), UTC_TIMESTAMP());';
}
$out[] = '';

$out[] = '-- ---------------------------------------------------------------- recipes';
foreach (seed_recipes() as $r) {
    $out[] = "INSERT INTO `{$p}recipes` (name, description, image, prep_minutes, cook_minutes, cook_notes, servings, difficulty, published, created_at, updated_at) VALUES ("
        . implode(', ', [q($r['name']), q($r['description']), q($r['image']), q($r['prep']), q($r['cook']), q($r['cook_notes']), q($r['servings']), q($r['difficulty'])]) . ', 1, UTC_TIMESTAMP(), UTC_TIMESTAMP());';
    $out[] = 'SET @rid = LAST_INSERT_ID();';
    foreach ($r['ingredients'] as $i => [$name, $qty, $unit, $notes]) {
        $out[] = "INSERT INTO `{$p}recipe_ingredients` (recipe_id, product_id, name, quantity, unit, notes, sort) VALUES (@rid, (SELECT id FROM `{$p}products` WHERE name = " . q($name) . '), '
            . q($name) . ', ' . q($qty) . ', ' . q($unit) . ', ' . q($notes) . ", $i);";
    }
    foreach ($r['steps'] as $i => $text) {
        $out[] = "INSERT INTO `{$p}recipe_steps` (recipe_id, sort, text) VALUES (@rid, $i, " . q($text) . ');';
    }
    $out[] = '';
}

$out[] = '-- ---------------------------------------------------------------- English translations of the content';
$j = function (array $a): string { return q(json_encode(['en' => array_filter($a, function ($v) { return $v !== null && $v !== ''; })], JSON_UNESCAPED_UNICODE)); };
foreach (seed_en_categories() as $it => [$name, $tip]) $out[] = "UPDATE `{$p}categories` SET i18n = " . $j(['name' => $name, 'expiry_tip' => $tip]) . ' WHERE name = ' . q($it) . ';';
foreach (seed_en_products() as $it => [$name, $tip]) $out[] = "UPDATE `{$p}products` SET i18n = " . $j(['name' => $name, 'expiry_tip' => $tip]) . ' WHERE name = ' . q($it) . ';';
foreach (seed_en_recipes() as $it => [$name, $desc, $cook, $steps, $notes]) {
    $out[] = "UPDATE `{$p}recipes` SET i18n = " . q(json_encode(['en' => ['name' => $name, 'description' => $desc, 'cook_notes' => $cook, 'steps' => $steps]], JSON_UNESCAPED_UNICODE)) . ' WHERE name = ' . q($it) . ';';
    foreach ($notes as $n_it => $n_en) {
        $out[] = "UPDATE `{$p}recipe_ingredients` i JOIN `{$p}recipes` r ON r.id = i.recipe_id SET i.i18n = " . $j(['notes' => $n_en]) . ' WHERE r.name = ' . q($it) . ' AND i.notes = ' . q($n_it) . ';';
    }
}
$out[] = '';

$file = __DIR__ . '/../install/foodtrack.sql';
file_put_contents($file, implode("\n", $out) . "\n");
echo "Written " . realpath($file) . "\n";

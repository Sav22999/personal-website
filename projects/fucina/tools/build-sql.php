<?php
/** Regenerates install/fucina.sql (tables and initial content for phpMyAdmin, prefix fc_): php tools/build-sql.php */
declare(strict_types=1);
require __DIR__ . '/../lib/bootstrap.php';
require __DIR__ . '/../lib/schema.php';
require __DIR__ . '/../lib/seed.php';
$p = 'fc_';
$out = ["-- Fucina — tables for phpMyAdmin (prefix {$p}). Generated by tools/build-sql.php. Alternative to install-db.php.", 'SET NAMES utf8mb4;', ''];
foreach (schema_statements($p) as $sql) $out[] = preg_replace('/\n\s+/', "\n  ", trim($sql)) . ";\n";
$out[] = "INSERT INTO `{$p}meta` (k, v) VALUES ('schema_version', '" . SCHEMA_VERSION . "') ON DUPLICATE KEY UPDATE v = VALUES(v);";
// Initial content. Questions find their lesson through its course and slug.
$q = fn($v) => $v === null ? 'NULL' : (is_int($v) ? (string)$v : "'" . str_replace(['\\', "'"], ['\\\\', "''"], (string)$v) . "'");
$rows = seed_rows();
foreach (['courses', 'lessons', 'games', 'game_items'] as $table) foreach ($rows[$table] as $r) {
    $out[] = "INSERT INTO `{$p}{$table}` (`" . implode('`,`', array_keys($r)) . '`) VALUES (' . implode(',', array_map($q, array_values($r))) . ');';
}
foreach ($rows['questions'] as $r) {
    [$course, $slug] = explode('/', $r['_lesson']);
    unset($r['_lesson']);
    $lesson = "(SELECT id FROM `{$p}lessons` WHERE course = " . $q($course) . ' AND slug = ' . $q($slug) . ')';
    $out[] = "INSERT INTO `{$p}questions` (lesson_id, `" . implode('`,`', array_keys($r)) . "`) VALUES ($lesson," . implode(',', array_map($q, array_values($r))) . ');';
}
foreach (seed_drills() as $lesson => $drills) {
    [$course, $slug] = explode('/', $lesson);
    foreach ($drills as $i => $d) {
        $kind = $d['kind'];
        unset($d['kind']);
        $out[] = "INSERT INTO `{$p}drills` (lesson_id, sort, kind, data) VALUES ((SELECT id FROM `{$p}lessons` WHERE course = " . $q($course) . ' AND slug = ' . $q($slug) . '),' . ($i + 1) . ',' . $q($kind) . ',' . $q(json_encode($d, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)) . ');';
    }
}
file_put_contents(__DIR__ . '/../install/fucina.sql', implode("\n", $out) . "\n");
echo "Written install/fucina.sql\n";
